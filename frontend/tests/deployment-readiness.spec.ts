for (const width of [390, 768, 1440]) test(`public pages and opportunity dialog remain usable at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 900 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  for (const route of ['/', '/careers', '/opportunities']) {
    await page.goto(route)
    await expect(page.locator('main')).toBeVisible()
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`${route.replaceAll('/', '') || 'home'}-${width}.png`), fullPage: true, animations: 'disabled' })
  }
  const search = page.getByRole('searchbox', { name: 'Search opportunities' })
  await search.fill('Data Scientist')
  const row = page.locator('.opp-row').filter({ has: page.getByRole('button', { name: 'Data Scientist', exact: true }) })
  await expect(row).toContainText('₹60 LPA')
  await expect(row).toContainText('5+ years')
  const opener = row.getByRole('button', { name: 'View Opportunity' })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: 'Job description' })
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('.opp-detail-title')).toHaveCSS('font-family', /DM Sans/)
  await expect(dialog).toContainText('₹60 LPA')
  await expect(dialog).toContainText('5+ years')
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Apply now' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Close job description' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
  await page.getByRole('link', { name: 'Back to enter' }).click()
  await expect(page).toHaveURL(/\/$/)
  expect(errors).toEqual([])
})

for (const kind of ['founding', 'leadership']) test(`${kind} rejects personal email and submits a work enquiry`, async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: kind === 'founding' ? 'Build Your Founding Team' : 'Find Leadership', exact: true }).first().click()
  const form = page.getByRole('form', { name: kind === 'founding' ? 'Founding team enquiry' : 'Leadership enquiry' })
  await form.getByLabel('Company', { exact: true }).fill('Synthetic Audit Company')
  await form.getByLabel('Your name', { exact: true }).fill('Synthetic Auditor')
  const email = form.getByLabel('Work email')
  await email.fill('audit@gmail.com')
  expect(await email.evaluate((e: HTMLInputElement) => e.checkValidity())).toBe(false)
  await email.fill('audit@company.example')
  expect(await email.evaluate((e: HTMLInputElement) => e.checkValidity())).toBe(true)
  if (kind === 'founding') {
    await form.getByText('Choose designation', { exact: true }).click()
    await form.getByRole('button', { name: 'Founder', exact: true }).click()
    await form.getByText('Choose location', { exact: true }).click()
    await form.getByRole('button', { name: 'Bengaluru', exact: true }).click()
    await form.getByLabel('What are you building?').fill('A synthetic product used only in the local audit.')
    await form.getByRole('button', { name: 'Founding Engineer', exact: true }).click()
  } else {
    await form.getByRole('button', { name: 'Engineering Leader', exact: true }).click()
    await form.getByLabel(/What needs to be fundamentally different/).fill('Improve delivery of a synthetic product.')
  }
  const response = page.waitForResponse(r => r.url().endsWith('/hiring/enquiries/') && r.request().method() === 'POST')
  await form.getByRole('button', { name: kind === 'founding' ? 'Build Your Founding Team' : 'Find Leadership', exact: true }).click()
  expect((await response).status()).toBe(201)
  await expect(form.getByRole('status')).toContainText('Your request has been received')
})

