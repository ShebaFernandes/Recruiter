  await page.getByRole('searchbox', { name: 'Search opportunities' }).fill('Data Scientist')
  await page.getByRole('button', { name: 'Data Scientist', exact: true }).click()
  await page.getByRole('button', { name: 'Apply now', exact: true }).click()
  await page.getByRole('button', { name: 'New here? Create an account' }).click()
  await page.getByLabel('Full name').fill('Synthetic Audit Applicant')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill('Audit-Applicant-Strong-123!')
