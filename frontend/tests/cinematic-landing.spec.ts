import { expect, test } from '@playwright/test'

for (const width of [390,768,1024,1440]) test(`restored landing ${width}`, async ({page}, info) => {
  await page.setViewportSize({width,height:1000})
  await page.route('**/api/v1/**',route=>route.fulfill({status:401,json:{}}))
  await page.goto('/')
  await expect(page.locator('.simple-landing')).toBeVisible()
  await expect(page.locator('.ce-company-preview')).toHaveCSS('background-color','rgba(0, 0, 0, 0)')
  await page.evaluate(()=>document.fonts.ready)
  await page.locator('.landing-background img').evaluateAll(async images=>Promise.all(images.map(img=>(img as HTMLImageElement).decode())))
  await expect(page.locator('.landing-background img')).toHaveCount(6)
  await expect(page.locator('video,.ce-product-preview,.ce-hero-actions')).toHaveCount(0)
  await expect(page.locator('.ce-intro h1')).toHaveCSS('animation-name','none')
  const scene=page.locator('.landing-background__scene')
  await expect(scene).toHaveCSS('animation-duration','28s')
  const clouds = page.locator('.landing-background__clouds-front')
  await expect(clouds).toHaveCSS('animation-name','landing-cloud-drift')
  await expect(clouds).toHaveCSS('animation-duration','18s')
  const startTransform = await clouds.evaluate(el => getComputedStyle(el).transform)
  await page.waitForTimeout(500)
  expect(await clouds.evaluate(el => getComputedStyle(el).transform)).not.toBe(startTransform)
  await expect(page.locator('.ce-nanonets-lockup').first()).toHaveText('Nanonets')
  await page.getByRole('button',{name:'Pause background animation'}).click()
  await expect(scene).toHaveCSS('animation-play-state','paused')
  await expect(clouds).toHaveCSS('animation-play-state','paused')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  await page.screenshot({path:info.outputPath(`restored-${width}.png`),fullPage:true})
  await page.getByText('Log in',{exact:true}).click()
  await expect(page.getByRole('button',{name:'Candidate log in'})).toBeVisible()
  await page.getByRole('button',{name:'Candidate log in'}).click()
  await expect(page.getByRole('heading',{name:'Welcome back'})).toBeVisible()
  await page.goto('/')
  await page.getByTestId('for-candidates').click()
  await expect(page.getByRole('heading',{name:'Create your account'})).toBeVisible()
  await page.goto('/')
  await page.getByTestId('for-recruiters').click()
  await expect(page.getByRole('heading',{name:'Welcome back'})).toBeVisible()
  await page.goto('/')
  await page.emulateMedia({reducedMotion:'reduce'})
  await expect(scene).toHaveCSS('animation-name','none')
  await expect(clouds).toHaveCSS('animation-name','none')
  await expect(page.locator('.landing-motion-toggle')).toBeHidden()
})
