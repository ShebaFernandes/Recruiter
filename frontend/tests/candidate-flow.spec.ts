test('real processing failure supports retry then successful replacement', async ({ page }, info) => {
  // Two real retry cycles each include the configured 30 + 60 second backoff.
  test.setTimeout(240_000)
  await signup(page, 'failure')
  const files = documents(info)
  await page.getByTestId('resume-input').setInputFiles({ name: 'broken.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7\nInvalid PDF fixture') })
  await expect(page.getByRole('heading', { name: 'We couldn’t finish this resume' })).toBeVisible({ timeout: 100_000 })
  await expect(page.locator('.processing-card')).not.toContainText(/\d+%/)
  const retried = page.waitForResponse(r => /\/resumes\/\d+\/retry\/$/.test(r.url()))
  await page.getByRole('button', { name: 'Retry processing' }).click()
  expect((await retried).status()).toBe(202)
  await expect(page.getByRole('heading', { name: "We're doing the boring part." })).toBeVisible()
  await expect(page.locator('.cp-processing-status')).toContainText(/Queued|Scanning|Processing/)
  await expect(page.getByRole('heading', { name: 'We couldn’t finish this resume' })).toBeVisible({ timeout: 100_000 })
  await page.getByLabel('Upload a replacement resume').setInputFiles(files.docx)
  await expect(page.locator('.career-journey .career-period')).toHaveCount(3, { timeout: 30_000 })
})
