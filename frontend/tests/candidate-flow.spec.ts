async function layouts(page: Page, info: TestInfo, state: string) {
  for (const width of [1440, 1024, 768, 390]) {
    await page.setViewportSize({ width, height: 900 })
    await page.evaluate(() => document.fonts.ready)
    // Let entrances play in the recording before capturing their final layout.
    await page.waitForTimeout(700)
    await page.evaluate(() => window.scrollTo(0, 0))
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    const cards = await page.locator('.candidate-experience > .cp-section').evaluateAll(elements => elements.map(el => el.getBoundingClientRect().width))
    if (cards.length > 1) expect(Math.max(...cards) - Math.min(...cards)).toBeLessThan(1)
    const controls = await page.locator('.cp-setting-row button, .cp-chips button, .cp-fields input:not([type=hidden]), .cp-fields select').evaluateAll(elements => elements.map(el => ({ height: el.getBoundingClientRect().height, compact: el.matches('.cp-beyond .cp-chips button') })))
    expect(controls.every(({ height, compact }) => height >= (width <= 640 ? 34 : compact ? 27 : 30))).toBe(true)
    await page.screenshot({ path: info.outputPath(`${state}-${width}.png`), fullPage: true, animations: 'disabled' })
  }
}

