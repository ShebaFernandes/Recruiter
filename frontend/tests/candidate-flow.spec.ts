async function signup(page: Page, suffix: string, startWorker = true) {
  const email = `candidate-redesign-${suffix}-${Date.now()}@example.com`
  await page.goto('/')
  await page.getByTestId('for-candidates').click()
  await page.getByLabel('Full name').fill('Career Test Candidate')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  const legalConfirmation = page.getByRole('checkbox', { name: /at least 18 years old.*Terms of Use/i })
  if (await legalConfirmation.count()) await legalConfirmation.check()
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Check your email' })).toBeVisible({ timeout: 20_000 })
  await page.goto(`/?verify-email=${issueLocalAccountToken(email, 'verify_email')}`)
  await expect(page.getByRole('heading', { name: 'Start with your resume' })).toBeVisible()
  if (!startWorker) return email
  // Process only this newly-created synthetic account's jobs. Never drain the user's queue.
  const worker = spawn(path.resolve('../.venv/bin/python'), ['-c', `import django, sys, time
django.setup()
from talent.models import ResumeProcessingJob
from talent.resume_processing import process_resume_job
email = sys.argv[1]
assert email.startswith('candidate-redesign-') and email.endswith('@example.com')
deadline = time.monotonic() + 240
while time.monotonic() < deadline:
    for job_id in ResumeProcessingJob.objects.filter(resume__candidate__user__email=email, state='queued').values_list('id', flat=True):
        process_resume_job(job_id)
    time.sleep(0.25)
`, email], { cwd: path.resolve('../backend'), stdio: 'ignore', env: { ...process.env, DJANGO_SETTINGS_MODULE: 'config.settings', DATABASE_URL: process.env.DATABASE_URL || 'postgresql://enter:enter@127.0.0.1:5433/enter', RESUME_AI_ENABLED: 'false' } })
  page.once('close', () => worker.kill())
  return email
}

