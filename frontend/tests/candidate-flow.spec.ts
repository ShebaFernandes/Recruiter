test('answer autosave preserves newer drafts, retries failures and flushes navigation', async ({ page }, info) => {
  test.setTimeout(90_000)
  await signup(page, 'autosave')
  await page.getByTestId('resume-input').setInputFiles(documents(info).docx)
  await page.getByRole('button', { name: "That's me ✓" }).click({ timeout: 30_000 })
  const answer = page.getByLabel("What is the most meaningful thing you've built?")
  let release = () => {}
  const held = new Promise<void>(resolve => { release = resolve })
  let started = false
  let count = 0
  await page.route('**/candidate/profile/', async route => {
    if (route.request().method() === 'PATCH') {
      count++
      if (count === 1) { started = true; await held }
    }
    await route.continue()
  })
  await answer.fill('First in-flight draft')
  await expect.poll(() => started).toBe(true)
  await answer.fill('Newest answer must win')
  expect(count).toBe(1)
  await expect(answer).toHaveValue('Newest answer must win')
  release()
  await expect.poll(() => count).toBe(2)
  await expect(page.getByRole('complementary', { name: 'Career Settings panel' })).toBeVisible()
  await page.unroute('**/candidate/profile/')
  await page.reload()
  await page.getByRole('button', { name: "That's me ✓" }).click()
  await expect(answer).toHaveValue('Newest answer must win')
  await page.route('**/candidate/profile/', route => route.request().method() === 'PATCH'
    ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"detail":"Synthetic save failure"}' }) : route.continue())
  await answer.fill('Never lose this answer')
  await expect(page.getByRole('button', { name: 'Retry saving answer' })).toBeVisible()
  await expect(answer).toHaveValue('Never lose this answer')
  await expect(page.getByRole('heading', { name: 'Career Settings', exact: true })).toHaveCount(0)
  page.once('dialog', dialog => void dialog.accept())
  await page.reload()
  await expect(answer).toHaveValue('Never lose this answer')
  await expect(page.getByRole('button', { name: 'Retry saving answer' })).toBeVisible()
  await page.unroute('**/candidate/profile/')
  await saved(page, () => page.getByRole('button', { name: 'Retry saving answer' }).click())
  await page.reload()
  await page.getByRole('button', { name: "That's me ✓" }).click()
  await expect(answer).toHaveValue('Never lose this answer')
  const longAnswer = 'A longer saved answer that wraps naturally across each dotted writing line. '.repeat(24)
  await saved(page, () => answer.fill(longAnswer))
  await expect(answer).toHaveAttribute('maxlength', '200')
  expect((await answer.inputValue()).length).toBeLessThanOrEqual(200)
  expect(await answer.evaluate(el => el.scrollHeight <= el.clientHeight)).toBe(true)
})

