import '@testing-library/jest-dom/vitest'
import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { api } from '../api'
import WhatAreYouBuilding from './WhatAreYouBuilding'

afterEach(() => {
  cleanup()
  vi.useRealTimers()
  vi.restoreAllMocks()
})

describe('WhatAreYouBuilding', () => {
  it('opens the hiring enquiry with blank fields', () => {
    render(<WhatAreYouBuilding />)
    fireEvent.click(screen.getByRole('button', { name: 'Find Talent' }))
    expect(screen.getByRole('dialog', { name: "Let's find your next great hire." })).toBeVisible()
    expect(screen.getByLabelText('Role or job title')).toHaveValue('Senior Frontend Engineer')
    fireEvent.click(screen.getByRole('button', { name: 'Close hiring enquiry' }))
    fireEvent.animationEnd(screen.getByRole('dialog'))
  })

  it('opens team and drive enquiries without prefilling fields', () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date(2026, 9, 28, 12))
    render(<WhatAreYouBuilding />)
    fireEvent.click(screen.getByRole('tab', { name: 'Build My Team' }))
    fireEvent.click(screen.getByRole('button', { name: 'Build My Team' }))
    expect(screen.getByRole('dialog', { name: "Let's build your team." })).toBeVisible()
    expect(screen.queryByLabelText('Team or department focus')).not.toBeInTheDocument()
    expect(screen.queryByLabelText('Exact openings')).not.toBeInTheDocument()
    fireEvent.keyDown(document, { key: 'Escape' })
    act(() => { vi.advanceTimersByTime(300) })
    fireEvent.click(screen.getByRole('tab', { name: 'Conduct a Recruitment Drive' }))
    fireEvent.click(screen.getByRole('button', { name: 'Plan My Drive' }))
    expect(screen.getByRole('dialog', { name: "Let's plan your hiring drive." })).toBeVisible()
    expect(screen.queryByLabelText('Exact openings')).not.toBeInTheDocument()
    expect(within(screen.getByRole('dialog')).queryByLabelText('Target hiring date')).not.toBeInTheDocument()
  })

  it('keeps an uploaded JD local and restores focus after closing', () => {
    vi.useFakeTimers()
    render(<WhatAreYouBuilding />)
    const opener = screen.getByRole('button', { name: 'Find Talent' })
    opener.focus()
    fireEvent.click(opener)
    const dialog = screen.getByRole('dialog')
    expect(within(dialog).getByRole('button', { name: 'Close hiring enquiry' })).toHaveFocus()
    const upload = within(dialog).getByLabelText("Upload JD's")
    fireEvent.change(upload, { target: { files: [new File(['test'], 'role.pdf', { type: 'application/pdf' })] } })
    expect(within(dialog).getByText('role.pdf')).toBeVisible()
    fireEvent.click(within(dialog).getByRole('button', { name: 'Remove' }))
    expect(within(dialog).queryByText('role.pdf')).toBeNull()
    fireEvent.click(within(dialog).getByRole('button', { name: 'Close hiring enquiry' }))
    act(() => { vi.advanceTimersByTime(300) })
    expect(screen.queryByRole('dialog')).toBeNull()
    expect(opener).toHaveFocus()
  })

  it('renders once with Hire Talent selected by default', () => {
    render(<WhatAreYouBuilding />)
    expect(screen.getAllByRole('heading', { name: 'What are you building next?' })).toHaveLength(1)
    expect(screen.getByRole('tab', { name: 'Hire Talent' })).toHaveAttribute('aria-selected', 'true')
    expect(screen.getByRole('button', { name: 'Find Talent' })).toBeVisible()
  })

  it('switches tabs with pointer and keyboard controls', () => {
    render(<WhatAreYouBuilding />)
    fireEvent.click(screen.getByRole('tab', { name: 'Build My Team' }))
    expect(screen.getByRole('button', { name: 'Build My Team' })).toBeVisible()

    const teamTab = screen.getByRole('tab', { name: 'Build My Team' })
    fireEvent.keyDown(teamTab, { key: 'ArrowRight' })
    expect(screen.getByRole('tab', { name: 'Conduct a Recruitment Drive' })).toHaveAttribute('aria-selected', 'true')
    expect(screen.getByRole('button', { name: 'Plan My Drive' })).toBeVisible()
  })

  it('keeps selected hiring values in frontend state', () => {
    render(<WhatAreYouBuilding />)
    fireEvent.click(screen.getByRole('button', { name: 'Role to hire: Senior Frontend Engineer' }))
    fireEvent.click(screen.getByRole('option', { name: 'Platform Engineer' }))
    fireEvent.click(screen.getByRole('button', { name: 'Hiring location: Hyderabad' }))
    fireEvent.click(screen.getByRole('option', { name: 'Pune' }))
    expect(screen.getByRole('button', { name: 'Role to hire: Platform Engineer' })).toBeVisible()
    expect(screen.getByRole('button', { name: 'Hiring location: Pune' })).toBeVisible()

    fireEvent.click(screen.getByRole('tab', { name: 'Build My Team' }))
    const panel = screen.getByRole('tabpanel')
    fireEvent.click(within(panel).getByRole('button', { name: 'Team size: 6 people' }))
    fireEvent.click(screen.getByRole('option', { name: '10 people' }))
    expect(within(panel).getByRole('button', { name: 'Team size: 10 people' })).toBeVisible()

    fireEvent.click(screen.getByRole('tab', { name: 'Conduct a Recruitment Drive' }))
    fireEvent.click(screen.getByRole('button', { name: 'Role for recruitment drive: Backend Engineers' }))
    fireEvent.click(screen.getByRole('option', { name: 'Data Engineers' }))
    fireEvent.click(screen.getByRole('button', { name: 'Recruitment drive location: Bengaluru' }))
    fireEvent.click(screen.getByRole('option', { name: 'Pune' }))
    expect(screen.getByRole('button', { name: 'Role for recruitment drive: Data Engineers' })).toBeVisible()
    expect(screen.getByRole('button', { name: 'Recruitment drive location: Pune' })).toBeVisible()
  })

  it('supports keyboard selection in compact dropdowns', () => {
    render(<WhatAreYouBuilding />)
    const roleTrigger = screen.getByRole('button', { name: 'Role to hire: Senior Frontend Engineer' })
    fireEvent.keyDown(roleTrigger, { key: 'ArrowDown' })
    fireEvent.keyDown(screen.getByRole('option', { name: 'Platform Engineer' }), { key: 'Enter' })
    expect(screen.getByRole('button', { name: 'Role to hire: Platform Engineer' })).toBeVisible()
  })

  it('allows future months while disabling past dates', () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date(2026, 9, 28, 12))
    render(<WhatAreYouBuilding />)
    fireEvent.click(screen.getByRole('tab', { name: 'Conduct a Recruitment Drive' }))

    fireEvent.click(screen.getByRole('button', { name: 'Recruitment drive deadline: 11 November 2026' }))
    expect(screen.getByRole('gridcell', { name: '27 November 2026' })).toBeEnabled()
    expect(screen.getByRole('gridcell', { name: '28 November 2026' })).toBeEnabled()
    fireEvent.click(screen.getByRole('button', { name: 'Previous month' }))
    expect(screen.getByRole('gridcell', { name: '28 October 2026' })).toHaveAttribute('aria-current', 'date')
    expect(screen.getByRole('gridcell', { name: '28 October 2026' })).toBeEnabled()
    expect(screen.getByRole('gridcell', { name: '27 October 2026' })).toBeDisabled()
    fireEvent.click(screen.getByRole('gridcell', { name: '28 October 2026' }))
    expect(screen.getByRole('button', { name: 'Recruitment drive deadline: 28 October 2026' })).toBeVisible()

    fireEvent.click(screen.getByRole('button', { name: 'Recruitment drive deadline: 28 October 2026' }))
    fireEvent.click(screen.getByRole('button', { name: 'Next month' }))
    fireEvent.click(screen.getByRole('button', { name: 'Next month' }))
    fireEvent.click(screen.getByRole('gridcell', { name: '15 December 2026' }))
    expect(screen.getByRole('button', { name: 'Recruitment drive deadline: 15 December 2026' })).toBeVisible()
  })

  it('closes dropdowns and the calendar with Escape', () => {
    render(<WhatAreYouBuilding />)
    const roleTrigger = screen.getByRole('button', { name: 'Role to hire: Senior Frontend Engineer' })
    fireEvent.click(roleTrigger)
    fireEvent.keyDown(screen.getByRole('option', { name: 'Senior Frontend Engineer' }), { key: 'Escape' })
    expect(screen.queryByRole('listbox', { name: 'Role to hire' })).not.toBeInTheDocument()

    fireEvent.click(screen.getByRole('tab', { name: 'Conduct a Recruitment Drive' }))
    const calendarTrigger = screen.getByRole('button', { name: /Recruitment drive deadline:/ })
    fireEvent.click(calendarTrigger)
    const selectedDate = screen.getByRole('gridcell', { selected: true })
    fireEvent.keyDown(selectedDate, { key: 'Escape' })
    expect(screen.queryByRole('dialog', { name: 'Choose recruitment drive deadline' })).not.toBeInTheDocument()
  })

  it('closes a dropdown when focus moves outside it', () => {
    render(<WhatAreYouBuilding />)
    const trigger = screen.getByRole('button', { name: 'Hiring location: Hyderabad' })
    fireEvent.click(trigger)
    expect(screen.getByRole('listbox', { name: 'Hiring location' })).toBeVisible()
    fireEvent.blur(trigger, { relatedTarget: document.body })
    expect(screen.queryByRole('listbox', { name: 'Hiring location' })).not.toBeInTheDocument()
  })

  it('validates and submits the selected hiring context', async () => {
    window.history.replaceState({}, '', '/')
    const submit = vi.spyOn(api, 'submitHiringEnquiry').mockResolvedValue({ id: 1, detail: 'Received' })
    render(<WhatAreYouBuilding />)
    fireEvent.click(screen.getByRole('button', { name: 'Find Talent' }))
    const dialog = screen.getByRole('dialog')
    fireEvent.change(within(dialog).getByLabelText('Role or job title'), { target: { value: 'Staff Backend Engineer' } })
    fireEvent.change(within(dialog).getByLabelText('Hiring location'), { target: { value: 'Delhi NCR' } })
    fireEvent.change(within(dialog).getByLabelText('Your name'), { target: { value: 'Alex' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Hiring manager' }))
    fireEvent.change(within(dialog).getByLabelText('Company name'), { target: { value: 'Example' } })
    fireEvent.change(within(dialog).getByLabelText('Work email'), { target: { value: 'alex@gmail.com' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Engineering' }))
    fireEvent.click(within(within(dialog).getByRole('group', { name: 'Role departments' })).getByRole('button', { name: 'Other' }))
    fireEvent.change(within(dialog).getByLabelText('Other department'), { target: { value: 'Design' } })
    fireEvent.click(within(dialog).getByRole('button', { name: '2 weeks' }))
    fireEvent.click(within(dialog).getByRole('button', { name: '30 days' }))
    expect(within(dialog).getByRole('button', { name: '2 weeks' })).toHaveAttribute('aria-pressed', 'false')
    fireEvent.click(within(within(dialog).getByRole('group', { name: 'How soon do you wish to close this position?' })).getByRole('button', { name: 'Other' }))
    fireEvent.change(within(dialog).getByLabelText('Other timeline'), { target: { value: '6 weeks' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Find Talent' }))
    expect(screen.getByText('Please use your company or work email address.')).toBeVisible()
    fireEvent.change(within(dialog).getByPlaceholderText('Work email'), { target: { value: 'alex@example.com' } })
    fireEvent.drop(dialog.querySelector('.enquiry-upload')!, {
      dataTransfer: { files: [new File(['%PDF-1.4'], 'role.pdf', { type: 'application/pdf' })] },
    })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Find Talent' }))
    expect(await screen.findByRole('status')).toHaveTextContent('Your request has been received.')
    expect(submit).toHaveBeenCalledOnce()
    const body = submit.mock.calls[0][0]
    expect(body.get('self_description')).toBe('Hiring manager')
    expect(body.get('how_soon')).toBe('Other')
    expect(body.get('how_soon_details')).toBe('6 weeks')
    expect(body.get('other_department')).toBe('Design')
    expect(body.get('kind')).toBe('hire')
    expect(body.get('role')).toBe('Staff Backend Engineer')
    expect(body.get('location')).toBe('Delhi NCR')
    expect(body.get('headcount')).toBe('1')
    expect(body.getAll('departments')).toEqual(['Engineering', 'Other'])
    expect((body.get('jd') as File).name).toBe('role.pdf')
    expect(window.location.pathname).toBe('/')
  })

  it('submits the selected team focus and size', async () => {
    const submit = vi.spyOn(api, 'submitHiringEnquiry').mockResolvedValue({ id: 2, detail: 'Received' })
    render(<WhatAreYouBuilding />)
    fireEvent.click(screen.getByRole('tab', { name: 'Build My Team' }))
    fireEvent.click(screen.getByRole('button', { name: 'Build My Team' }))
    const dialog = screen.getByRole('dialog', { name: "Let's build your team." })
    fireEvent.change(within(dialog).getByLabelText('Your name'), { target: { value: 'Alex' } })
    fireEvent.change(within(dialog).getByLabelText('Company name'), { target: { value: 'Example' } })
    fireEvent.change(within(dialog).getByLabelText('Work email'), { target: { value: 'alex@example.com' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Engineering' }))
    fireEvent.click(within(dialog).getByRole('button', { name: 'Build My Team' }))
    expect(await screen.findByRole('status')).toHaveTextContent('Your request has been received.')
    const body = submit.mock.calls[0][0]
    expect(body.get('kind')).toBe('team')
    expect(body.get('team_focus')).toBe('Backend Engineering')
    expect(body.get('headcount')).toBe('6')
    expect(body.getAll('departments')).toEqual(['Engineering'])
  })

  it('submits the recruitment drive deadline and location', async () => {
    const submit = vi.spyOn(api, 'submitHiringEnquiry').mockResolvedValue({ id: 3, detail: 'Received' })
    render(<WhatAreYouBuilding />)
    fireEvent.click(screen.getByRole('tab', { name: 'Conduct a Recruitment Drive' }))
    fireEvent.click(screen.getByRole('button', { name: 'Plan My Drive' }))
    const dialog = screen.getByRole('dialog', { name: "Let's plan your hiring drive." })
    fireEvent.change(within(dialog).getByLabelText('Your name'), { target: { value: 'Alex' } })
    fireEvent.change(within(dialog).getByLabelText('Company name'), { target: { value: 'Example' } })
    fireEvent.change(within(dialog).getByLabelText('Work email'), { target: { value: 'alex@example.com' } })
    fireEvent.click(within(dialog).getByRole('button', { name: 'Engineering' }))
    fireEvent.click(within(dialog).getByRole('button', { name: 'Plan My Drive' }))
    expect(await screen.findByRole('status')).toHaveTextContent('Your request has been received.')
    const body = submit.mock.calls[0][0]
    expect(body.get('kind')).toBe('drive')
    expect(body.get('role')).toBe('Backend Engineers')
    expect(body.get('location')).toBe('Bengaluru')
    expect(body.get('headcount')).toBe('12')
    expect(body.get('deadline')).toMatch(/^\d{4}-\d{2}-\d{2}$/)
  })

  it('dismisses the calendar from month controls and outside pointer clicks', () => {
    render(<WhatAreYouBuilding />)
    fireEvent.click(screen.getByRole('tab', { name: 'Conduct a Recruitment Drive' }))
    const trigger = screen.getByRole('button', { name: /Recruitment drive deadline:/ })
    fireEvent.click(trigger)
    fireEvent.keyDown(screen.getByRole('button', { name: 'Previous month' }), { key: 'Escape' })
    expect(screen.queryByRole('dialog')).toBeNull()
    expect(trigger).toHaveFocus()
    fireEvent.click(trigger)
    fireEvent.pointerDown(document.body)
    expect(screen.queryByRole('dialog')).toBeNull()
  })

  it('handles year boundaries and refreshes an expired date when the page regains focus', () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date(2026, 11, 20, 23, 30))
    render(<WhatAreYouBuilding />)
    fireEvent.click(screen.getByRole('tab', { name: 'Conduct a Recruitment Drive' }))
    fireEvent.click(screen.getByRole('button', { name: /Recruitment drive deadline:/ }))
    expect(screen.getByRole('gridcell', { name: '19 January 2027' })).toBeEnabled()
    expect(screen.getByRole('gridcell', { name: '20 January 2027' })).toBeEnabled()
    fireEvent.click(screen.getByRole('button', { name: 'Previous month' }))
    fireEvent.click(screen.getByRole('gridcell', { name: '20 December 2026' }))
    act(() => { vi.setSystemTime(new Date(2026, 11, 22, 9)); window.dispatchEvent(new Event('focus')) })
    expect(screen.getByRole('button', { name: 'Recruitment drive deadline: 22 December 2026' })).toBeVisible()
  })
})
